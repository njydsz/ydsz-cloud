package com.njydsz.pmis.common.lock.annotation;

/**
 * 锁类型枚举
 *
 * <p>定义支持的分布式锁类型，不同锁类型适用于不同场景。
 *
 * @author ydsz-pmis-team
 * @since 1.0.0
 * @since 1.0.0
 */
public enum LockType {

    /**
     * 可重入锁
     * <p>同一线程可多次获取同一把锁，内部维护重入计数
     * <p>适用于：方法嵌套调用、递归调用等场景
     */
    REENTRANT,

    /**
     * 公平锁
     * <p>按客户端请求顺序获取锁，先到先得
     * <p>适用于：需要严格按顺序执行的分布式任务
     */
    FAIR,

    /**
     * 读写锁
     * <p>读锁共享，写锁独占，支持读读并发、读写互斥、写写互斥
     * <p>适用于：读多写少场景，如配置缓存、元数据查询等
     */
    READ_WRITE,

    /**
     * 信号量
     * <p>控制同时访问资源的并发数量，支持有限资源池的并发控制
     * <p>适用于：连接池限流、并发任务数控制等场景
     */
    SEMAPHORE
}

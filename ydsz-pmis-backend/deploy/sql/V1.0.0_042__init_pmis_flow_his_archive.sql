SELECT 'pmis_flow_his_instance' AS table_name, COUNT(*) AS column_count
FROM information_schema.columns
WHERE table_name = 'pmis_flow_his_instance'
UNION ALL
SELECT 'pmis_flow_his_variable' AS table_name, COUNT(*) AS column_count
FROM information_schema.columns
WHERE table_name = 'pmis_flow_his_variable';
